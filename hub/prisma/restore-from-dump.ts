async function restoreTaskLogs() {
  console.log('Restoring task logs...');
  const content = fs.readFileSync(path.join(DUMP_DIR, 'task_logs.csv'), 'utf-8');
  const logs = parseCSV(content);
  
  const batchSize = 100;
  for (let i = 0; i < logs.length; i += batchSize) {
    const batch = logs.slice(i, i + batchSize);
    await Promise.all(
      batch.map(log =>
        prisma.taskLog.create({
          data: {
            id: parseInt(log.id),
            taskId: parseInt(log.taskId),
            userId: parseInt(log.userId),
            text: log.text || null,
            createdAt: new Date(log.createdAt),
            updatedAt: new Date(log.updatedAt),
          },
        }).catch(() => null)
      )
    );
    if (i % 1000 === 0) {
      console.log(`  Processed ${i}/${logs.length} logs...`);
    }
  }
  console.log(`  Restored ${logs.length} task logs`);
}

