// Parse CSV content — handles quoted fields containing newlines
function parseCSV(content: string): Record<string, string>[] {
  const headers = content.trim().split('\n')[0].split(',');

  const rows: string[][] = [];
  let currentRow: string[] = [];
  let currentField = '';
  let inQuotes = false;
  let idx = content.indexOf('\n');
  if (idx !== -1) idx = content.indexOf('\n', idx + 1); // skip header line

  const body = idx === -1 ? '' : content.slice(idx + 1);

  for (let i = 0; i < body.length; i++) {
    const char = body[i];
    const nextChar = body[i + 1];

    if (char === '"') {
      if (inQuotes && nextChar === '"') {
        currentField += '"';
        i++;
      } else {
        inQuotes = !inQuotes;
      }
    } else if (char === ',' && !inQuotes) {
      currentRow.push(currentField.replace(/^"|"$/g, '').replace(/""/g, '"'));
      currentField = '';
    } else if (char === '\n' && !inQuotes) {
      currentRow.push(currentField.replace(/^"|"$/g, '').replace(/""/g, '"'));
      rows.push(currentRow);
      currentRow = [];
      currentField = '';
    } else {
      currentField += char;
    }
  }
  if (currentField || currentRow.length > 0) {
    currentRow.push(currentField.replace(/^"|"$/g, '').replace(/""/g, '"'));
    rows.push(currentRow);
  }

  return rows.map(values => {
    const record: Record<string, string> = {};
    headers.forEach((header, i) => {
      record[header] = values[i] || '';
    });
    return record;
  });
}

// Anonymize email by replacing domain with example.com
function anonymizeEmail(email: string): string {
  const [localPart] = email.split('@');
  return `${localPart}@example.com`;
}

async function restoreUsers() {
  console.log('Restoring users...');
  const content = fs.readFileSync(path.join(DUMP_DIR, 'users.csv'), 'utf-8');
  const users = parseCSV(content);
  
  for (const user of users) {
    try {
      const anonymizedEmail = anonymizeEmail(user.email);
      await prisma.user.create({
        data: {
          id: parseInt(user.id),
          name: user.name,
          surname: user.surname || null,
          email: anonymizedEmail,
          password: null,
          avatarUrl: user.avatarUrl || null,
          role: resolveUserRole(user, anonymizedEmail),
          createdAt: new Date(user.createdAt),
          updatedAt: new Date(user.updatedAt),
        },
      });
      console.log(`  Created user: ${anonymizedEmail}`);
    } catch (e) {
      console.error(`  Failed to create user ${user.email}:`, e);
    }
  }
}

