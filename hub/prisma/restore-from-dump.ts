async function main() {
  console.log('Starting data restoration from CSV dumps...\n');
  
  console.log('Clearing existing data...');
  await prisma.taskLog.deleteMany();
  await prisma.taskComment.deleteMany();
  await prisma.task.deleteMany();
  await prisma.projectColumn.deleteMany();
  await prisma.projectUser.deleteMany();
  await prisma.project.deleteMany();
  await prisma.user.deleteMany();
  console.log('Cleared existing data\n');
  
  await restoreUsers();
  await restoreProjects();
  await restoreProjectColumns();
  await restoreProjectUsers();
  await restoreTasks();
  await restoreTaskComments();
  await restoreTaskLogs();
  await restoreProjectDocuments();
  await restoreTaskDocumentLinks();
  
  console.log('\nSetting default password for all users...');
  await prisma.$executeRaw`
    UPDATE "User" 
    SET password = ${BETTER_AUTH_HASH}
    WHERE password IS NULL
  `;
  console.log('Default password set (admin1234)');
  
  console.log('\nCreating Better Auth Account records...');
  const allUsers = await prisma.user.findMany();
  for (const user of allUsers) {
    await prisma.$executeRaw`
      INSERT INTO "Account" ("userId", "accountId", "providerId", "password", "createdAt", "updatedAt")
      VALUES (${user.id}, ${user.id.toString()}, 'credential', ${BETTER_AUTH_HASH}, NOW(), NOW())
      ON CONFLICT ("providerId", "accountId") DO NOTHING
    `;
  }
  console.log(`Created ${allUsers.length} Account records`);
  
  console.log('\n✅ Data restoration complete!');
  console.log('\nAll users can now login with: <email> / admin1234');
}

main()
  .catch((e) => {
    console.error('Restoration failed:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });