/** Seed dump: this local-part always maps to example.com and must be system ADMIN */
const SYSTEM_ADMIN_LOCAL = 'lukaszpodlipskikontakt';

function resolveUserRole(row: Record<string, string>, anonymizedEmail: string): UserRole {
  const raw = (row.role ?? '').trim().toUpperCase();
  if (raw === 'ADMIN' || raw === 'SUPPORT' || raw === 'USER') {
    return UserRole[raw as keyof typeof UserRole];
  }
  const local = anonymizedEmail.split('@')[0] ?? '';
  if (local === SYSTEM_ADMIN_LOCAL) return UserRole.ADMIN;
  return UserRole.USER;
}

